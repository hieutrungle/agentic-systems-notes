"""Block 02 figures agree with the controller lab.

The figure includes under docs/curriculum/_figures/ are generated by
docs/assets/diagrams/controller_figures.py. These tests parse the committed HTML
and compare every row number and trace value with labs.controller.
"""
from __future__ import annotations

import importlib.util
import unittest
from html.parser import HTMLParser
from pathlib import Path

from labs import controller as lab

ROOT = Path(__file__).resolve().parents[1]
FIGURES = ROOT / "docs" / "curriculum" / "_figures"
GENERATOR = ROOT / "docs" / "assets" / "diagrams" / "controller_figures.py"


def load_generator():
    spec = importlib.util.spec_from_file_location("controller_figures", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class Steps(HTMLParser):
    """Collect each step list's <li> attributes and the text of its state fields."""

    def __init__(self):
        super().__init__()
        self.lists: dict[str, list[dict]] = {}
        self.current: list[dict] | None = None
        self.field: str | None = None
        self.in_dd = False
        self.depth = 0

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "ol" and "data-steps" in a:
            self.current = self.lists.setdefault(a.get("data-scenario", "main"), [])
            self.depth = 0
        elif self.current is not None and tag == "li" and self.depth == 0:
            self.current.append({**a, "fields": {}, "checkpoint": None})
            self.depth = 1
        elif self.current is not None and self.depth:
            if tag == "li":
                self.depth += 1
            if tag == "dl" and "data-checkpoint" in a:
                self.current[-1]["checkpoint"] = int(a["data-checkpoint"])
            if tag == "div" and "data-field" in a:
                self.field = a["data-field"]
            if tag == "dd" and self.field:
                self.in_dd = True
                self.current[-1]["fields"][self.field] = ""

    def handle_endtag(self, tag):
        if tag == "dd":
            self.in_dd = False
            self.field = None
        if self.current is not None and tag == "li" and self.depth:
            self.depth -= 1
        if tag == "ol" and self.current is not None and self.depth == 0:
            self.current = None

    def handle_data(self, data):
        if self.in_dd and self.current:
            self.current[-1]["fields"][self.field] += data


def parse(name: str) -> dict[str, list[dict]]:
    parser = Steps()
    parser.feed((FIGURES / name).read_text(encoding="utf-8"))
    return parser.lists


class FigureParityTest(unittest.TestCase):
    def test_includes_match_generator(self):
        generated = load_generator().render()
        for name, text in generated.items():
            with self.subTest(figure=name):
                self.assertEqual((FIGURES / name).read_text(encoding="utf-8"), text,
                                 f"{name} is stale: run python docs/assets/diagrams/controller_figures.py")

    def test_build_adds_each_main_row_once(self):
        steps = parse("controller-states.html")["main"]
        rows = [int(s["data-current"]) for s in steps[1:-1]]
        self.assertEqual(sorted(rows), list(range(1, 14)))
        self.assertEqual(steps[-1]["data-current"], "3 4")
        self.assertEqual(steps[-1]["data-shown"].split(), [str(r) for r in rows])

    def test_build_rows_use_lab_modes(self):
        generator = load_generator()
        by_ref = {}
        for row in lab.ROWS:
            by_ref.setdefault(row.ref, row)
        for ref in range(1, 14):
            frm, to = generator.ROWS[ref][:2]
            lab_row = by_ref[ref]
            if frm != "Any mode in Search":
                self.assertIn(frm.lower(), lab_row.modes, ref)
            if lab_row.next != "=":
                self.assertEqual(to.lower(), lab_row.next, ref)

    def test_traces_match_lab(self):
        traces = parse("controller-trace.html")
        self.assertEqual(set(traces), {"ordinary", "lost-score", "cancel"})
        for name, steps in traces.items():
            log = lab.run(lab.SCENARIOS[name])
            with self.subTest(scenario=name):
                self.assertEqual(len(steps), len(log) + 1)
                self.assertEqual(steps[0]["checkpoint"], 0)
                for step, entry in zip(steps[1:], log):
                    z = entry.record
                    self.assertEqual(int(step["data-current"]), entry.row.ref)
                    self.assertEqual(step["data-mode"], entry.next)
                    self.assertEqual(step["checkpoint"], z.checkpoint)
                    f = step["fields"]
                    self.assertTrue(f["mode"].lower().startswith(z.mode), (f["mode"], z.mode))
                    self.assertTrue(f["incumbent"].startswith(f"{z.incumbent} · {z.incumbent_score:.3f}"))
                    self.assertEqual(f["compute"], f"{z.unspent:.1f} GPU-h unspent · {z.reserved:.1f} reserved")
                    self.assertEqual(f["counters"], f"{z.trials_used} of 5 trials · {z.proposals_used} of 10 proposals")
                    if z.pending is None:
                        self.assertTrue(f["pending"].startswith("None"))
                    else:
                        self.assertTrue(f["pending"].startswith(z.pending.trial))

    def test_published_trace_values(self):
        traces = parse("controller-trace.html")
        self.assertEqual([s["checkpoint"] for s in traces["ordinary"]], list(range(0, 9)))
        self.assertEqual([s["checkpoint"] for s in traces["lost-score"]], list(range(0, 11)))
        kept = [s for s in traces["ordinary"] if s["fields"]["incumbent"] == "t1 · 0.851"]
        self.assertTrue(kept)
        self.assertEqual(kept[0]["fields"]["compute"], "1.4 GPU-h unspent · 0.0 reserved")

    def test_upstream_moves_every_enforced_rule_once(self):
        steps = parse("controller-upstream.html")["main"]
        moved = steps[-1]["data-moved"].split()
        self.assertEqual(len(moved), len(set(moved)))
        generator = load_generator()
        movable = {key for key, _, runtime in generator.LANES if runtime}
        self.assertEqual(set(moved), movable)


if __name__ == "__main__":
    unittest.main()
